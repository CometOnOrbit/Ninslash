@dataclass(frozen=True)
class LevelValues:
	values: tuple
	def at(self, level):
		return self.values[level]

def levels(*values):
	if len(values) != LEVEL_COUNT:
		raise ValueError("weapon level curve must contain 16 values")
	return LevelValues(values)

def _f32(value):
	return struct.unpack("f", struct.pack("f", float(value)))[0]

def _charge(level, max_level):
	return _f32(level / float(max(1, max_level)))

def linear(base, amount, max_level):
	base = _f32(base)
	amount = _f32(amount)
	return LevelValues(tuple(_f32(base + _f32(_charge(level, max_level) * amount)) for level in range(LEVEL_COUNT)))

def integer_linear(base, amount, max_level):
	return LevelValues(tuple(int(value) for value in linear(base, amount, max_level).values))

def cost_curve(base_cost, level_cost, max_level):
	level_cost = _f32(level_cost)
	values = []
	for level in range(LEVEL_COUNT):
		charge = _charge(level, max_level)
		cost = _f32(level_cost * charge)
		cost = _f32(cost * _f32(_f32(charge * _f32(0.25)) + _f32(0.75)))
		values.append(int(_f32(base_cost + cost)))
	return LevelValues(tuple(values))

def resolve(value, level=0):
	return value.at(level) if isinstance(value, LevelValues) else value

