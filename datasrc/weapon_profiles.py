def cursor_weapon(key, level):
	num_weapons = len(content.container.weapons.id.items)
	if key[0] == "static":
		value = level * 4096 + STATIC_NAMES.index(key[1]) * 16 + 9
	else:
		value = level * 4096 + (weapon_types.PART2_NAMES.index(key[2]) + 1) * 256 + (weapon_types.PART1_NAMES.index(key[1]) + 1) * 16 + 1
	return value % num_weapons

def _cpp(value, integer=False):
	if isinstance(value, bool):
		return "true" if value else "false"
	if integer:
		return str(int(value))
	if math.isinf(value):
		return "WEAPON_INFINITE_PROJECTILE_LIFETIME"
	literal = format(float(value), ".9g")
	if "." not in literal and "e" not in literal:
		literal += ".0"
	return literal + "f"

